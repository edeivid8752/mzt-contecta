import assert from 'node:assert/strict';
import {roleLabel, selectTrends, avatarInitial, authorByline} from '../src/community-v12.js';
assert.equal(roleLabel('editor'),'Editor');
assert.equal(roleLabel('lector'),'Lector');
assert.equal(roleLabel('ciudadano'),'Ciudadano');
assert.equal(roleLabel('admin'),'Rol no disponible');
assert.equal(authorByline('vecino','ciudadano'),'@vecino · Ciudadano');
assert.equal(authorByline('editor','editor'),'@editor · Editor');
assert.equal(authorByline('lector','lector'),'@lector · Lector');
assert.equal(avatarInitial('  María '),'M');
assert.equal(avatarInitial(''),'U');
const now=Date.parse('2026-11-24T12:00:00Z'),day=86400000;
const p=(id,age,review='approved',votes=0)=>({id,review,createdAt:new Date(now-age).toISOString(),votes});
const rows=[p('old',7*day+1,'approved',99),p('boundary',7*day,'approved',98),p('recent',day,'approved',3),p('pending',day,'pending',100),p('future',-1,'approved',100),p('newest',1,'approved',3),p('near-boundary',7*day-1,'approved',5),...Array.from({length:5},(_,i)=>p('extra'+i,2*day+i,'approved',1))];
const before=JSON.stringify(rows);
assert.deepEqual(selectTrends(rows,x=>x.votes,now).map(x=>x.id),['near-boundary','newest','recent','extra0','extra1']);
assert.equal(JSON.stringify(rows),before);
assert.deepEqual(selectTrends([],x=>x.votes,now),[]);
assert.deepEqual(selectTrends([p('old',7*day)],x=>x.votes,now),[]);
console.log('v1.2: roles, avatar y tendencias OK');
