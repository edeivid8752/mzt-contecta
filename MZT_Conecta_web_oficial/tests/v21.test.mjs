import assert from 'node:assert/strict';
import {parseRoute,postPath,threadPath,profilePath,slug,authPaths,viewPaths,sections,forumCategories} from '../src/router-v21.js';
const id='12345678-1234-1234-1234-123456789abc';
assert.deepEqual(parseRoute('/'),{view:'explorar',section:'news',mode:'explorar'});
for(const [key,path] of Object.entries(authPaths))assert.equal(parseRoute(path).auth,key);
for(const [key,path] of Object.entries(viewPaths))assert.equal(parseRoute(path).view,key);
for(const [key,path] of Object.entries(sections))assert.equal(parseRoute('/muro/'+path).section,key);
for(const c of forumCategories)assert.equal(parseRoute('/foro/'+slug(c)).topic,c);
assert.equal(parseRoute('/muro/siguiendo').mode,'siguiendo');
assert.equal(parseRoute(postPath({title:'¡Corte de agua en Mazatlán!',id})).id,id);
assert.equal(parseRoute(postPath({title:'Otro título',id})).id,id);
assert.equal(parseRoute('/','?post='+id).id,id);
assert.equal(parseRoute(threadPath({title:'Qué hacer',id})).thread,id);
assert.equal(parseRoute(profilePath({username:'jaime.iz'},'followers')).mode,'followers');
assert.equal(parseRoute(profilePath({username:'jaime.iz'},'following')).mode,'following');
assert.equal(parseRoute('/perfil/jaime.iz').username,'jaime.iz');
assert.equal(parseRoute('/publicacion/invalida').invalid,true);
assert.equal(parseRoute('/perfil/%2f').invalid,true);
assert.equal(parseRoute('/foro/').view,'foro');
console.log('Pruebas de rutas v2.1 correctas');
